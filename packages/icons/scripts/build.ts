// Turns every drawing in svg/ into a React component in src/generated/, and writes src/index.ts.
// Run it with `pnpm --filter @manasbal/icons build:icons` after adding or changing a drawing.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { transform, type Config } from "@svgr/core";
import jsx from "@svgr/plugin-jsx";
import { format, resolveConfig } from "prettier";
import { optimize } from "svgo";

const HEADER = "// Generated by `pnpm --filter @manasbal/icons build:icons`. Do not edit.\n";

/** `shopping-bag.svg` -> `ShoppingBagIcon` */
export function componentName(file: string): string {
  const words = path.basename(file, ".svg").split("-");
  return `${words.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("")}Icon`;
}

// SVGO only tidies the file: comments, metadata and ids go. Nothing else runs, so every path
// keeps its exact `d` and the icon draws the same as the drawing (src/icons.test.tsx checks it).
export function optimizeSvg(source: string): string {
  return optimize(source, {
    plugins: ["removeComments", "removeMetadata", "cleanupIds"],
  }).data;
}

// The <svg> becomes <Icon {...props}>: the frame and line settings live in Icon.tsx, set once for
// every icon, so a component holds only its shapes.
const template: Config["template"] = ({ componentName: name, jsx: element }, { tpl }) => {
  element.openingElement.name = { type: "JSXIdentifier", name: "Icon" };
  element.closingElement!.name = { type: "JSXIdentifier", name: "Icon" };
  element.openingElement.attributes = [
    { type: "JSXSpreadAttribute", argument: { type: "Identifier", name: "props" } },
  ];
  return tpl`
import { Icon, type IconProps } from "../Icon";

export function ${name}(props: IconProps) {
  return ${element};
}
`;
};

// Formatted with the repo's Prettier settings (looked up from this script, so a build into any
// folder formats the same), so the committed files are stable.
async function formatTs(code: string, file: string): Promise<string> {
  const options = await resolveConfig(import.meta.filename);
  return format(code, { ...options, filepath: file });
}

export async function iconSource(svg: string, name: string, file: string): Promise<string> {
  const code = await transform(
    optimizeSvg(svg),
    { plugins: [jsx], typescript: true, jsxRuntime: "automatic", template },
    { componentName: name },
  );
  return formatTs(HEADER + code, file);
}

/** Builds every icon from svgDir into srcDir/generated and writes srcDir/index.ts. */
export async function buildIcons(svgDir: string, srcDir: string): Promise<void> {
  const files = readdirSync(svgDir)
    .filter((file) => file.endsWith(".svg"))
    .sort((a, b) => a.localeCompare(b));
  const generatedDir = path.join(srcDir, "generated");
  rmSync(generatedDir, { recursive: true, force: true });
  mkdirSync(generatedDir, { recursive: true });

  const names: string[] = [];
  for (const file of files) {
    const name = componentName(file);
    names.push(name);
    const svg = readFileSync(path.join(svgDir, file), "utf8");
    const target = path.join(generatedDir, `${name}.tsx`);
    writeFileSync(target, await iconSource(svg, name, target));
  }

  const exports = names.map((name) => `export { ${name} } from "./generated/${name}";\n`);
  const index = path.join(srcDir, "index.ts");
  const code = `${HEADER}export { Icon, type IconProps, type IconSize } from "./Icon";\n${exports.join("")}`;
  writeFileSync(index, await formatTs(code, index));
}
